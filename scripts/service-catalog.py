#!/usr/bin/env python3
"""Write docs/services.md from the homelab.* labels in every <category>/<service>/compose.yaml.

Usage: scripts/service-catalog.py [--root DIR] [--check]
       scripts/service-catalog.py -h|--help

Default: (re)writes docs/services.md: one table per homelab.group (name, path, port, audience,
description; homelab.external.<id>.* tiles included, no port), then the compose services that carry
no homelab.* labels (sidecars, databases, helpers).
--check      write nothing; exit 1 when docs/services.md is stale, or when the CLAUDE.md Ports table
             disagrees with the homelab.port labels:
               missing   a homelab.port with no row in the table
               service   the row names a different service than the label's
               extra     a row with no homelab.port, unless the named service publishes that host port
                         (ports:) or runs with network_mode: host (e.g. 53, 80, 445, 8043)
             scripts/check.sh runs it.
--root DIR   repo root (default: the parent of scripts/).

Exit codes: 0 written / up to date, 1 --check findings, 2 usage error (bad flag, missing root).
Stdlib + PyYAML; reuses compose-lint.py's file walk, label and Ports-table parsing.
"""
import importlib.util
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join("docs", "services.md")

_spec = importlib.util.spec_from_file_location("compose_lint", os.path.join(HERE, "compose-lint.py"))
lint = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(lint)


def usage(msg):
    print(f"service-catalog: {msg}\nUsage: scripts/service-catalog.py [--root DIR] [--check] (--help)",
          file=sys.stderr)
    sys.exit(2)


def host_ports(svc):
    """Host ports a service publishes, short ("[ip:]host:container[/proto]") or long syntax."""
    out = set()
    for p in svc.get("ports") or []:
        if isinstance(p, dict):
            pub = str(p.get("published", "")).split("-")[0]
        else:
            parts = str(p).split("/")[0].rsplit(":", 2)
            pub = parts[-2].split("-")[0] if len(parts) >= 2 else ""
        if pub.isdigit():
            out.add(int(pub))
    return out


def collect(root):
    """(tiles, unlabelled, services). tiles: dicts with group/name/path/port/audience/description/svc;
    unlabelled: [(path, service)]; services: {service: {"ports": set, "host": bool}}."""
    tiles, unlabelled, services = [], [], {}
    for path in lint.find_compose_files(root):
        rel = os.path.relpath(path, root).replace(os.sep, "/")
        try:
            with open(path, encoding="utf-8") as f:
                doc = yaml.safe_load(f) or {}
        except (OSError, yaml.YAMLError) as e:
            print(f"service-catalog: {rel}: skipped ({e.__class__.__name__})", file=sys.stderr)
            continue
        svcs = doc.get("services") if isinstance(doc, dict) else None
        if not isinstance(svcs, dict):
            continue
        for name, svc in svcs.items():
            svc = svc if isinstance(svc, dict) else {}
            services[name] = {"ports": host_ports(svc), "host": svc.get("network_mode") == "host"}
            labels = lint.labels_of(svc)
            if not any(k.startswith("homelab.") for k in labels):
                unlabelled.append((rel, name))
                continue
            if "homelab.name" in labels or "homelab.port" in labels:
                port = labels.get("homelab.port", "")
                tiles.append({
                    "svc": name, "path": rel,
                    "port": int(port) if port.isdigit() else None,
                    **{f: labels.get(f"homelab.{f}", "") for f in
                       ("name", "group", "audience", "description")},
                })
            ext = {}
            for k, v in labels.items():
                if k.startswith("homelab.external."):
                    tid, _, field = k[len("homelab.external."):].partition(".")
                    ext.setdefault(tid, {})[field] = v
            for tid, f in sorted(ext.items()):
                tiles.append({
                    "svc": name, "external": tid, "path": rel, "port": None,
                    **{k: f.get(k, "") for k in ("name", "group", "audience", "description")},
                })
    return tiles, unlabelled, services


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def render(tiles, unlabelled):
    lines = [
        "# Services",
        "",
        "Generated by `scripts/service-catalog.py` from the `homelab.*` compose labels; do not edit by hand.",
        "Re-run it after changing a label; `scripts/check.sh` fails while this file is stale.",
        "External tiles (`homelab.external.<id>.*`) have no port and no link.",
    ]
    groups = sorted({t["group"] or "(no group)" for t in tiles}, key=str.lower)
    for g in groups:
        lines += ["", f"## {g}", "", "| Name | Path | Port | Audience | Description |", "|---|---|---|---|---|"]
        rows = [t for t in tiles if (t["group"] or "(no group)") == g]
        for t in sorted(rows, key=lambda t: (t["name"].lower(), t["path"])):
            where = f"`{t['path']}`"
            if t.get("external"):
                where += f" (external `{cell(t['external'])}`)"
            elif t["svc"] != t["path"].split("/")[1]:
                where += f" ({cell(t['svc'])})"
            port = str(t["port"]) if t["port"] is not None else "-"
            lines.append(f"| {cell(t['name'])} | {where} | {port} | {cell(t['audience'])} | "
                         f"{cell(t['description'])} |")
    lines += ["", "## Compose services with no homelab labels", ""]
    if unlabelled:
        by_path = {}
        for path, name in unlabelled:
            by_path.setdefault(path, []).append(name)
        for path in sorted(by_path):
            lines.append(f"- `{path}`: {', '.join(sorted(by_path[path]))}")
    else:
        lines.append("None.")
    return "\n".join(lines) + "\n"


def port_findings(root, tiles, services):
    table = lint.ports_table(root)
    labelled = {t["port"]: t for t in tiles if t["port"] is not None}
    out = []
    for port, t in sorted(labelled.items()):
        if port not in table:
            out.append(f"missing: {t['path']} homelab.port={port} ({t['svc']}) has no CLAUDE.md Ports row")
        elif table[port] != t["svc"]:
            out.append(f"service: CLAUDE.md Ports row {port} names {table[port]!r}, "
                       f"homelab.port={port} is on {t['svc']!r} ({t['path']})")
    for port, svc in sorted(table.items()):
        if port in labelled:
            continue
        info = services.get(svc)
        if info is None:
            out.append(f"extra: CLAUDE.md Ports row {port} names {svc!r}: no such compose service "
                       "and no homelab.port label")
        elif port not in info["ports"] and not info["host"]:
            out.append(f"extra: CLAUDE.md Ports row {port} ({svc}): no homelab.port label and "
                       f"{svc} does not publish it")
    return out


def main(argv):
    root, check = os.path.dirname(HERE), False
    args = list(argv)
    while args:
        a = args.pop(0)
        if a in ("-h", "--help"):
            print(__doc__.strip())
            return 0
        if a == "--check":
            check = True
        elif a == "--root":
            if not args:
                usage("--root needs a directory")
            root = args.pop(0)
        else:
            usage(f"unknown argument {a!r}")
    if not os.path.isdir(root):
        usage(f"root {root!r} is not a directory")

    tiles, unlabelled, services = collect(root)
    text = render(tiles, unlabelled)
    out = os.path.join(root, OUT)
    if not check:
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"service-catalog: wrote {OUT} ({len(tiles)} tiles, {len(unlabelled)} unlabelled services)")
        return 0

    findings = []
    try:
        with open(out, encoding="utf-8") as f:
            current = f.read()
    except OSError:
        current = None
    if current != text:
        findings.append(f"stale: {OUT} {'is missing' if current is None else 'differs from the labels'}; "
                        "run scripts/service-catalog.py")
    findings += port_findings(root, tiles, services)
    for line in findings:
        print(f"service-catalog: {line}")
    if findings:
        return 1
    print(f"service-catalog: {OUT} up to date, Ports table matches the labels")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
